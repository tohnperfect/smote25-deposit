#!/usr/bin/env python3
"""WP2 step 1: build the JAIR-format version of the draft from the integrated-draft sources (v0.2 onwards).

The draft sources (main.tex, sec/, gen/, refs.bib, figures/) stay the only place
where text is edited; this script regenerates the JAIR build from them every time.
It takes the class files and the preamble of the team's JAIR main file
(jair.cls 2025/08/15 on acmart 2.12, BibLaTeX + Biber, acmauthoryear) unchanged,
sets the confirmed title, converts the abstract to JAIR's structured form,
converts natbib citations to BibLaTeX (\\citet -> \\textcite, \\citep -> \\parencite),
hides the provenance tags (\\provfalse) and keeps the [Team: ...] notes visible.
Usage: python3 scripts/to_jair.py <team-repo-root> <draft-dir> <out-dir>
Build: cd <out-dir>; pdflatex main; biber main; pdflatex main; pdflatex main
"""
import re
import shutil
import sys
from pathlib import Path

repo, src, out = (Path(a) for a in sys.argv[1:4])
if out.exists():
    shutil.rmtree(out)
(out / 'sec').mkdir(parents=True)
(out / 'gen').mkdir()
for f in ('jair.cls', 'acmart.cls', 'acmauthoryear.bbx', 'acmauthoryear.cbx', 'acmdatamodel.dbx'):
    shutil.copy(repo / f, out / f)
shutil.copytree(src / 'figures', out / 'figures')

CITE = [(re.compile(r'\\citet(\[[^\]]*\])?\{'), r'\\textcite\1{'),
        (re.compile(r'\\citep(\[[^\]]*\])?\{'), r'\\parencite\1{')]


def conv(text):
    for pat, rep in CITE:
        text = pat.sub(rep, text)
    return text


for f in sorted((src / 'sec').glob('*.tex')):
    (out / 'sec' / f.name).write_text(conv(f.read_text(encoding='utf-8')), encoding='utf-8')
for f in sorted((src / 'gen').glob('*.tex')):
    (out / 'gen' / f.name).write_text(conv(f.read_text(encoding='utf-8')), encoding='utf-8')

# bibliography: drop the provenance field "status", which the BibLaTeX data model does not know
bib = (src / 'refs.bib').read_text(encoding='utf-8')
bib = re.sub(r',\s*status=\{[^{}]*\}', '', bib)
(out / 'references.bib').write_text(bib, encoding='utf-8')

# abstract: v0.2 "\textbf{Background.} ..." -> JAIR "{\bf Background:} ..." paragraphs
vmain = (src / 'main.tex').read_text(encoding='utf-8')
abstract = vmain[vmain.index('\\begin{abstract}') + len('\\begin{abstract}'):vmain.index('\\end{abstract}')]
abstract = re.sub(r'\\src\{[A-Z]\}\{[^}]*\}', '', abstract.replace('\\noindent', '')).strip()   # v0.18: any tag (S, A)
abstract = re.sub(r'\\textbf\{(Background|Objectives|Methods|Results|Conclusions)\.\}\s*', r'\n\n{\\bf \1:}\n', abstract).strip()
inputs = re.findall(r'\\input\{(sec/[^}]+)\}', vmain[:vmain.index('\\bibliographystyle')])
appendix = re.findall(r'\\input\{(sec/[^}]+)\}', vmain[vmain.index('\\appendix'):])

team = (repo / 'main.tex').read_text(encoding='utf-8')
pre = team[:team.index('\\begin{document}')]
pre = pre.replace('\\newcommand{\\TODO}[1]{\\textcolor{red}{[TODO: #1]}}', r"""\newcommand{\TODO}[1]{\textcolor{red}{[TODO: #1]}}

%% SMOTE25 helpers (content macros only; no style change). Generated by scripts/to_jair.py.
\usepackage{tabularx}
\newcolumntype{L}[1]{>{\raggedright\arraybackslash}p{#1}}
\newcolumntype{Y}{>{\raggedright\arraybackslash}X}
\newif\ifprov \provfalse  % provenance tags of the integrated draft, hidden in the JAIR build
\newcommand{\src}[2]{\ifprov{\sffamily\scriptsize[#1 #2]}\ \fi}
\newcommand{\team}[1]{{\sffamily\footnotesize\textcolor{red}{[Team: #1]}}}  % open items: none may remain at submission
\newcommand{\tabnote}[1]{\par\smallskip{\footnotesize #1}}
% v0.39: the reference style puts a literal period before the year, which doubled the dot of "et al." (et al..);
% \addperiod lets biblatex merge the two
\xpatchbibmacro{date+extradate}{\setunit*{.\space}}{\setunit*{\addperiod\space}}{}{}
% v0.62 (team lead, 23 Nov 2026): the first submission does not print the lines "JAIR Associate Editor" and "JAIR
% Reference Format" (placeholders that JAIR fills at acceptance). For the camera-ready version remove this line.
\settopmatter{printacmref=false}""")
body = team[team.index('\\begin{document}'):]
body = re.sub(r'\\title\[[^\]]*\]\{[^}]*\}',
              lambda m: r'\title[SMOTE 25 Years of Magic]{SMOTE 25 Years of Magic: What Has Been Done, What the Evidence Shows, and Whom It Reached}',
              body, count=1)
# v0.4 (decision D5, 10 Nov 2026): the author block of the team main file holds placeholders; replace it with
# the decided authors in the decided order (e-mails, affiliations and the corresponding author's ORCID: 11 Nov 2026).
AUTHORS = r"""%% Authors (decision D5, 10 Nov 2026); e-mails, affiliations and ORCID from the team lead, 11 Nov 2026.
\author{Thanapong Intharah}
\authornote{Corresponding Author.}
\orcid{0000-0003-0965-680X}
\email{thanin@kku.ac.th}
\affiliation{%
  \department{Visual Intelligence Laboratory (VILab), Department of Statistics, Faculty of Science}
  \institution{Khon Kaen University}
  \city{Khon Kaen}
  \country{Thailand}
}

\author{Pharamut Makjaroen}
\email{pharamut@kkumail.com}
\affiliation{%
  \department{Visual Intelligence Laboratory (VILab), Department of Statistics, Faculty of Science}
  \institution{Khon Kaen University}
  \city{Khon Kaen}
  \country{Thailand}
}

\author{Kanvara Thawarorit}
\email{kanvara.t@kkumail.com}
\affiliation{%
  \department{Department of Statistics, Faculty of Science}
  \institution{Khon Kaen University}
  \city{Khon Kaen}
  \country{Thailand}
}

\author{Supawit Chaingam}
\email{supawit.c@kkumail.com}
\affiliation{%
  \department{Department of Statistics, Faculty of Science}
  \institution{Khon Kaen University}
  \city{Khon Kaen}
  \country{Thailand}
}

\renewcommand{\shortauthors}{Intharah, Makjaroen, Thawarorit and Chaingam}
"""
au0 = body.index('\\author{')
au1 = body.index('\n', body.index('\\renewcommand{\\shortauthors}')) + 1
body = body[:au0] + AUTHORS + body[au1:]
a0, a1 = body.index('\\begin{abstract}'), body.index('\\end{abstract}')
body = body[:a0] + '\\begin{abstract}\n' + abstract + '\n' + body[a1:]
m0 = body.index('\\maketitle') + len('\\maketitle')
m1 = body.index('%% Acknowledgments')
body = body[:m0] + '\n\n' + '\n'.join(f'\\input{{{s}}}' for s in inputs) + '\n\n' + body[m1:]
# v0.23 (D55, 14 Nov 2026): no acknowledgments. Drop the template's acks environment and its TODO; the funding
# statement is in the Declarations after the Conclusion (sec/10-closing.tex).
k0 = body.index('%% Acknowledgments')
k1 = body.index('\\end{acks}', k0) + len('\\end{acks}')
inner = body[k0:k1].split('\\begin{acks}', 1)[1].rsplit('\\end{acks}', 1)[0].strip()
assert inner.startswith('\\TODO{') and inner.count('\n') == 0, 'the acks environment holds text: ' + inner
body = body[:k0] + body[k1:].lstrip('\n')
body = re.sub(r'\\appendix\s*\n\\input\{sections/appendix-reproducibility\}',
              lambda m: '\\appendix\n' + '\n'.join(f'\\input{{{s}}}' for s in appendix), body)
(out / 'main.tex').write_text(
    '%% GENERATED by scripts/to_jair.py from the draft sources and the team JAIR main file. Do not edit; edit the sources and regenerate.\n'
    + pre + body, encoding='utf-8')
print(f'wrote {out}/main.tex with {len(inputs)} body inputs and {len(appendix)} appendix inputs')
