#!/usr/bin/env python3
"""Appendix table of benchmark candidates (W3 of the readiness assessment).

The Data draft's Table 1 says its first rule (datasets used by ten or more papers)
selects 33 datasets but prints only the 10 of them that were on the initial list.
This table prints every dataset that meets either rule, from the Data section's own
file, so that the table and the rule agree.
Usage: python3 scripts/gen_benchmark_candidates.py "<team-repo>/Data section/out/benchmark_candidates.csv" gen/table_benchmark_candidates.tex
"""
import csv
import sys
from pathlib import Path

rows = list(csv.DictReader(open(sys.argv[1], encoding='utf-8-sig')))
GROUP = {'frequently used benchmark': 'F', 'potential diversity candidate': 'D', 'requires verification': 'V'}
ORDER = {'F': 0, 'D': 1, 'V': 2}


def rng(vals):
    v = sorted({int(x) for x in vals.split(';') if x.strip().isdigit()})
    if not v:
        return 'n/p'
    return f'{v[0]:,}' if len(v) == 1 else f'{v[0]:,}--{v[-1]:,}'


def tex(s):
    return s.replace('_', r'\_').replace('&', r'\&').replace('%', r'\%')


rows.sort(key=lambda r: (ORDER[GROUP[r['group']]], -int(r['papers']), r['name']))
out = ['% Generated by scripts/gen_benchmark_candidates.py from Data section/out/benchmark_candidates.csv. Do not edit by hand.']
for r in rows:
    g = GROUP[r['group']]
    out.append(f"{tex(r['name'])} & {g} & {r['papers']} & {r['family_papers']} & {rng(r['n_instances_values'])} & "
               f"{r['n_instances_printed']}/{r['entries']} & {r['modified_entries']}/{r['entries']} & "
               f"{'yes' if r['listed_in_task'] == 'yes' else ''} \\\\")
out.append(r'\bottomrule')
Path(sys.argv[2]).write_text('\n'.join(out) + '\n', encoding='utf-8')
n = {k: sum(1 for r in rows if GROUP[r['group']] == k) for k in 'FDV'}
print(f"wrote {sys.argv[2]}: {len(rows)} datasets (F {n['F']}, D {n['D']}, V {n['V']}); on the initial list: "
      f"{sum(1 for r in rows if r['listed_in_task'] == 'yes')}")
