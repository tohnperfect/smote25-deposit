#!/usr/bin/env python3
"""Tables of the independent benchmark (WP6) for Appendix F, generated from the test files.

Reads benchmark/results_summary/<tier>/tests_vs_smote.csv and writes gen/table_benchmark_<tier>.tex: one row per
method, the median over families of (method minus SMOTE) for four measures and two learners, signed so that a
positive value means the method did better than SMOTE (for the Brier score, a lower score); a star marks a Holm
adjusted Wilcoxon p below 0.05. Also writes benchmark/results_summary/headline.json with the numbers the text uses.
Usage: python3 -I scripts/gen_benchmark_tables.py <draft root>
"""
import json
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(sys.argv[1])
NAMES = [('none', 'No resampling'), ('class_weight', 'Class weights'), ('threshold', 'Tuned threshold'),
         ('ROS', 'Random oversampling'), ('ADASYN', 'ADASYN'), ('Borderline-SMOTE', 'Borderline-SMOTE'),
         ('G-SMOTE', 'Geometric SMOTE'), ('Safe-Level-SMOTE', 'Safe-Level-SMOTE'), ('Cluster-SMOTE', 'Cluster-SMOTE'),
         ('k-means SMOTE', '$k$-means SMOTE'), ('MWMOTE', 'MWMOTE'), ('SMOTE-IPF', 'SMOTE-IPF'), ('A-SUWO', 'A-SUWO')]
MEAS = [('roc_auc', 'ROC'), ('pr_auc', 'PR'), ('gmean', 'G'), ('brier', 'Brier')]
LEARNERS = ['RF', 'GB']


def cell(t, method, learner, measure):
    r = t[(t.method == method) & (t.learner == learner) & (t.measure == measure)]
    if r.empty:
        return '--'
    r = r.iloc[0]
    v = r.median_diff_vs_smote
    star = r.holm_p < 0.05
    if abs(v) < 0.0005:   # rounds to zero: no sign, unless the difference is significant (the sign then gives its direction)
        s = ('$-$0.000' if v < 0 else '+0.000') if star else '0.000'
    else:
        s = f"{v:+.3f}".replace('-', '$-$')
    return s + ('$^{*}$' if star else '')


headline = {}
for tier in ('core', 'nested'):
    t = pd.read_csv(ROOT / f'benchmark/results_summary/{tier}/tests_vs_smote.csv')
    lines = []
    for key, label in NAMES:
        if t[t.method == key].empty:
            continue
        lines.append(label + ' & ' + ' & '.join(cell(t, key, ln, m) for ln in LEARNERS for m, _ in MEAS) + r' \\')
    nf = int(t[t.learner.isin(LEARNERS)].n_friedman.max())
    (ROOT / f'gen/table_benchmark_{tier}.tex').write_text(
        f'% generated by scripts/gen_benchmark_tables.py from benchmark/results_summary/{tier}/tests_vs_smote.csv\n'
        + '\n'.join(lines) + '\n\\bottomrule\n')   # the rule goes inside the file: \input then \bottomrule fails
    sig = t[(t.holm_p < 0.05)]
    headline[tier] = dict(
        n_friedman_max=nf,
        better_than_smote=sorted(set(map(tuple, sig[sig.median_diff_vs_smote > 0][['learner', 'measure', 'method']].values.tolist()))),
        worse_than_smote=sorted(set(map(tuple, sig[sig.median_diff_vs_smote < 0][['learner', 'measure', 'method']].values.tolist()))),
        comparisons=len(t), significant=len(sig))
(ROOT / 'benchmark/results_summary/headline.json').write_text(json.dumps(headline, indent=1))
for k, v in headline.items():
    print(k, 'comparisons', v['comparisons'], 'significant', v['significant'], 'families (max)', v['n_friedman_max'])
