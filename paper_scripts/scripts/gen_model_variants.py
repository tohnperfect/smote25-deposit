#!/usr/bin/env python3
"""M8: one table with every model variant of the Data analyses, with labels and a
Holm correction over the exploratory family of difficulty predictors.
v0.4 (decision D19, 10 Nov 2026): no hypothesis was fixed in advance, so every model is labelled exploratory.

Reads Data section/out/hypotheses.json and Data section/out/difficulty_outcomes.json
(team repository, read only); writes gen/table_model_variants.tex and prints the
Holm-adjusted p-values quoted in Section 5.4.
Usage: python3 scripts/gen_model_variants.py "<team-repo>/Data section/out" gen/table_model_variants.tex
v0.16 (decision D35, 12 Nov 2026): run on data/d35/out, the Data outputs recomputed with the first-named variant of
the four papers that propose several (data/d35/README.md):
       python3 scripts/gen_model_variants.py data/d35/out gen/table_model_variants.tex
v0.16, later the same day: when <out>/full_precision/ holds the two files at full precision (data/d35/tools/full_precision.py),
they are read instead, so that every value is rounded once (the Data scripts write three decimals; rounding 1.2145 to
1.215 and then to 1.22 moved a printed value).
"""
import json
import sys
from pathlib import Path

out_dir = Path(sys.argv[1])
fp = out_dir / 'full_precision'
full = (fp / 'hypotheses.json').exists() and (fp / 'difficulty_outcomes.json').exists()
in_dir = fp if full else out_dir
h = json.loads((in_dir / 'hypotheses.json').read_text(encoding='utf-8'))
d = json.loads((in_dir / 'difficulty_outcomes.json').read_text(encoding='utf-8'))


def holm(ps):
    order = sorted(range(len(ps)), key=lambda i: ps[i])
    adj, run = [None] * len(ps), 0.0
    for rank, i in enumerate(order):
        run = max(run, min(1.0, (len(ps) - rank) * ps[i]))
        adj[i] = run
    return adj


def fmt_p(p):
    return '$<$0.001' if p < 0.001 else (f'{p:.3f}' if p < 0.1 else f'{p:.2f}')


def ci(c):
    return f'{c[0]:.2f} to {c[1]:.2f}'


rows = []
H = h['all_metric_plain']['H1_primary_modsyn_vs_original']
rows.append(('Modified or synthetic vs original (H1)', 'Paper-clustered GEE', 'exploratory', H['M1_gee']['odds_ratio'],
             ci(H['M1_gee']['ci95']), fmt_p(H['M1_gee']['p']), 'none (one question)'))
rows.append(('', 'Conditional logistic, within 12 papers', 'exploratory', H['M2_conditional']['odds_ratio'],
             ci(H['M2_conditional']['ci95']), fmt_p(H['M2_conditional']['p']), ''))
rows.append(('', 'Bayesian mixed model (95\\% interval)', 'exploratory', H['M3_bayes_mixed']['odds_ratio'],
             ci(H['M3_bayes_mixed']['ci95_approx']), '', ''))
rows.append(('', 'Crude, Fisher exact', 'exploratory', H['crude']['odds_ratio'], '', fmt_p(H['crude']['fisher_p']), ''))
H2 = h['all_metric_plain']['H1_modsyn_vs_standard']
rows.append(('Modified or synthetic vs original or repository-defined', 'Paper-clustered GEE', 'exploratory',
             H2['M1_gee']['odds_ratio'], ci(H2['M1_gee']['ci95']), fmt_p(H2['M1_gee']['p']), ''))
rows.append(('', 'Conditional logistic', 'exploratory', H2['M2_conditional']['odds_ratio'],
             ci(H2['M2_conditional']['ci95']), fmt_p(H2['M2_conditional']['p']), ''))

# v0.63: the two other ways of counting that Section 5.5 of the paper names (note 14 of the read-through of 23 Nov 2026)
for _key, _lab in (('robust_R1_dataset_majority', 'H1 with one result per dataset'),
                   ('robust_R2_ruleA', 'H1 with one metric per paper')):
    _H = h[_key]['H1_primary_modsyn_vs_original']
    rows.append((_lab, 'Paper-clustered GEE', 'exploratory', _H['M1_gee']['odds_ratio'], ci(_H['M1_gee']['ci95']),
                 fmt_p(_H['M1_gee']['p']), ''))
    rows.append(('', f"Conditional logistic, within {_H['M2_conditional']['papers_informative']} papers", 'exploratory',
                 _H['M2_conditional']['odds_ratio'], ci(_H['M2_conditional']['ci95']), fmt_p(_H['M2_conditional']['p']), ''))

M = d['models']
preds = [('noise_per_0.1', 'Noise index, per 0.1'), ('log2_IR', 'Imbalance ratio, per doubling'),
         ('small_sample', 'Small-sample flag'), ('outlier_flag', 'Outlier flag'), ('small_disjuncts', 'Small-disjunct flag')]
for model, mlabel in (('gee', 'Paper-clustered GEE'), ('within_paper', 'Within papers')):
    ps = [M[k][model]['p'] for k, _ in preds]
    adj = holm(ps)
    for (k, lab), p, a in zip(preds, ps, adj):
        rows.append((lab, mlabel, 'exploratory', M[k][model]['odds_ratio'], '', fmt_p(p), fmt_p(a)))
        print(f'{mlabel:22} {lab:32} OR {M[k][model]["odds_ratio"]:.3f}  p {p:.4f}  Holm {a:.4f}')

src = 'data/d35/out' if out_dir.parts[-2:] == ('d35', 'out') else 'Data section/out'
src += '/full_precision' if full else ''
lines = [f'% Generated by scripts/gen_model_variants.py from {src}/hypotheses.json and difficulty_outcomes.json. Do not edit by hand.']
for r in rows:
    q, model, label, orr, c, p, adj = r
    lines.append(f'{q} & {model} & {label} & {orr:.2f} & {c} & {p} & {adj} \\\\')
lines.append(r'\bottomrule')
Path(sys.argv[2]).write_text('\n'.join(lines) + '\n', encoding='utf-8')
print(f'wrote {sys.argv[2]} ({len(rows)} rows)')
