#!/usr/bin/env python3
"""Table 17 (tab:recommend) of the paper, from the rerun on the reference collection (WP6.8 step 3, v0.10).

Reads benchmark/results_summary/rerun42/c1_rerun.csv and summary.json (written by
benchmark/rerun42/scripts/stats42.py) and writes gen/table_recommend.tex: the tabular of Table 17 with, for each of the
ten simple methods that keep all data (C2 and C3), the difference from SMOTE that its own paper prints (from the Method
section's Table 7, M 10, as v0.9 printed it), the implementation used in the rerun and how it was checked, the median
difference from SMOTE in the rerun (ROC-AUC and PR-AUC, random forest / gradient boosting, over families of tasks),
and criterion C1 from the rerun; then the four baselines of Section 9.1 against SMOTE.
Usage: python3 -I scripts/gen_recommend_table.py DRAFT_DIR
"""
import csv
import json
import sys
from pathlib import Path

R = Path(sys.argv[1])
S = R / 'benchmark/results_summary/rerun42'
# method -> (label in the table, class, paper's difference as Table 7 prints it, decisions changed, implementation)
TEN = [
    ('SMOTE', 'SMOTE (2002)', 'B', 'ref.', 'none', 'imblearn'),
    ('Cluster-SMOTE', 'Cluster-SMOTE (2006)', 'B', 'plots', 'partner', 'smote-var.'),
    ('ADASYN', 'ADASYN (2008)', 'B', '+.015 (5/5)', 'allocation', 'imblearn'),
    ('Safe-Level-SMOTE', 'Safe-Level-SMOTE (2009)', 'B', 'plots', 'seed, placement', 'smote-var.'),
    ('CGMOS', 'CGMOS (2016)', 'B', '+.009 (24/30)', 'seed', 'ours, not repr.'),
    ('SMOM', 'SMOM (2017)', 'M', '+.004 (19/27)', 'partner', 'ours, repr.'),
    ('G-SMOTE', 'G-SMOTE (2019)', 'B', 'avg.', 'partner, placement', 'imblearn-extra'),
    ('AB-SMOTE', 'AB-SMOTE (2020)', 'B', '$-$.029 (2/8)', 'seed, partner', 'ours, repr.'),
    ('RSMOTE', 'RSMOTE (2021)', 'B+M', '+.021 (21/27)', 'seed, allocation', 'ours, not repr.'),
    ('FW-SMOTE', 'FW-SMOTE (2022)', 'B', '+.018 (30/42)', 'partner', 'ours, close'),
]
BASE = [('none', 'No resampling'), ('class_weight', 'Class weights'), ('threshold', 'Tuned threshold'),
        ('ROS', 'Random oversampling')]
c1 = {r['method']: r for r in csv.DictReader(open(S / 'c1_rerun.csv', encoding='utf-8'))}
summ = json.load(open(S / 'summary.json', encoding='utf-8'))


def d(x):
    if x in (None, '', 'None', 'nan'):
        return 'n/a'
    v = float(x)
    s = f'{abs(v):.3f}'.lstrip('0')
    return ('$-$' if v < -0.0005 else '+' if v > 0.0005 else '') + (s if abs(v) >= 0.0005 else '.000')


def pair(r, ms):
    return f"{d(r.get(f'{ms}_RF'))}/{d(r.get(f'{ms}_GB'))}"


L = ['\\begin{tabular}{@{}lll>{\\raggedright\\arraybackslash}p{1.75cm}lll>{\\raggedright\\arraybackslash}p{1.9cm}@{}}', '\\toprule',
     ' & & Paper: & & \\multicolumn{2}{l}{Rerun: $\\Delta$ vs SMOTE, RF/GB} & & \\\\',
     'Method & Class & $\\Delta$ vs SMOTE & Code & ROC-AUC & PR-AUC & C1 & Decisions changed \\\\', '\\midrule']
for m, label, cls, paper, dec, impl in TEN:
    if m == 'SMOTE':
        L.append(f'{label} & {cls} & {paper} & {impl} & ref. & ref. & ref. & {dec} \\\\')
        continue
    r = c1[m]
    L.append(f"{label} & {cls} & {paper} & {impl} & {pair(r, 'roc_auc')} & {pair(r, 'pr_auc')} & {r['c1_rerun'].replace('not testable', 'n.t.')} & {dec} \\\\")
L.append('\\midrule')
for m, label in BASE:
    r = c1[m]
    L.append(f"{label} & & & & {pair(r, 'roc_auc')} & {pair(r, 'pr_auc')} & & \\\\")
L += ['\\bottomrule', '\\end{tabular}']
out = R / 'gen/table_recommend.tex'
out.write_text('% Generated by scripts/gen_recommend_table.py from benchmark/results_summary/rerun42/; do not edit by hand.\n'
               + '\n'.join(L) + '\n', encoding='utf-8')
print('wrote', out.relative_to(R), f"({summ['tasks']} tasks in {summ['families']} families)")
