#!/usr/bin/env python3
"""Rows of the table that sets the coverage sample against the curated corpus (WP4, Section 4.4).

Sample values come from data/search/screening_full_2026-11-11/samples/samples_summary.json (scripts/analyze_samples.py);
corpus values are the counts printed elsewhere in the paper, each with the section it comes from (they are not
recomputed here). Writes gen/table_coverage_rows.tex.
Usage: python3 -I scripts/gen_coverage_table.py DRAFT_DIR
"""
import json
import sys
from pathlib import Path

# v0.37: importable (scripts/search_numbers.py checks the wording of Section 4.4 against these rows)

# corpus: (count, base, where the paper prints it)
CORPUS = {
    'core': (34, 47, 'Sec. 3.3: Core 34 of the 47 corpus papers that generate synthetic minority examples'),
    'partial': (3, 47, 'Sec. 3.3: Partial 3'),
    'notcounted': (10, 47, 'Sec. 3.3: ten Not counted papers generate synthetic minority examples'),
    'S': (24, 36, 'Sec. 4.1'), 'A': (21, 36, 'Sec. 4.1'), 'N': (22, 36, 'Sec. 4.1'), 'P': (13, 36, 'Sec. 4.1'),
    'F': (12, 36, 'Sec. 4.1'), 'L': (8, 36, 'Sec. 4.1'),
    'B': (24, 37, 'Sec. 4.2'), 'M': (5, 37, 'Sec. 4.2'), 'B+M': (8, 37, 'Sec. 4.2'),
    'vs_smote_plain': (44, 73, 'Sec. 6.4: plain SMOTE in 44 of the 73 papers with an evaluation on data'),
    'vs_none': (52, 71, 'Sec. 6.4'),
    'gmean': (41, 71, 'Sec. 6.2'),
    'repeated': (43, 71, 'Sec. 6.3'),
    'inside': (34, 71, 'Sec. 6.3'),
    'tuning_test': (35, 71, 'Sec. 6.3, Figure 5'),
    'stat_test': (52, 71, 'Sec. 6.5'),
    'code': (27, 71, 'Sec. 6.6'),
}


def pc(k, n):
    return f'{round(100 * k / n)}' if n else '--'


def cell_c(key):
    k, n = CORPUS[key][:2]
    return f'{k} of {n} ({pc(k, n)}\\%)'


def cell_s(d):
    if not d or not d['n']:
        return '--'
    lo, hi = d['ci95']
    return f"{d['k']} of {d['n']} ({pc(d['k'], d['n'])}\\%; {round(lo)}--{round(hi)})"


def rows_for(s):
    """(label, corpus key, sample entry) for every row; s is the pooled coverage block of samples_summary.json."""
    return [
        ('Core: interpolation is the main generator', 'core', s['label']['Core']),
        ('Partial: interpolation is one of several generators', 'partial', s['label']['Partial']),
        ('Not counted: generates in another way', 'notcounted', s['label']['Not counted']),
        ('\\multicolumn{3}{l}{\\emph{Decisions changed (Core and Partial variants)}}', None, None),
        ('Seed selection (S)', 'S', s['decisions']['S']),
        ('Sample allocation (A)', 'A', s['decisions']['A']),
        ('Neighbor choice (N)', 'N', s['decisions']['N']),
        ('Placement rule (P)', 'P', s['decisions']['P']),
        ('Post-filtering (F)', 'F', s['decisions']['F']),
        ('Inside a pipeline (L)', 'L', s['decisions']['L']),
        ('\\multicolumn{3}{l}{\\emph{Class category}}', None, None),
        ('Binary only', 'B', s['class']['B']),
        ('Multiclass only', 'M', s['class']['M']),
        ('Binary and multiclass', 'B+M', s['class']['B+M']),
        ('\\multicolumn{3}{l}{\\emph{Evaluation}}', None, None),
        ('Plain SMOTE among the competitors', 'vs_smote_plain', s['vs_smote_plain']),
        ('Learner without resampling among the competitors', 'vs_none', s['vs_none']),
        ('G-mean reported', 'gmean', s['measures']['G-mean']),
        ('Repeated partitions', 'repeated', s['repeated']),
        ('Resampling inside the training folds stated', 'inside', s['inside_stated']),
        ('Settings chosen on test scores', 'tuning_test', s['tuning_test']),
        ('Significance test', 'stat_test', s['stat_test']),
        ('Code released', 'code', s['code']),
    ]


if __name__ == '__main__':
    R = Path(sys.argv[1])
    s = json.load(open(R / 'data/search/screening_full_2026-11-11/samples/samples_summary.json', encoding='utf-8'))['coverage']['pooled']
    # the first group heading is in the table itself (a \multicolumn cannot open an \input file inside a tabular)
    lines = []
    for label, key, d in rows_for(s):
        if key is None:
            lines.append(f'{label} \\\\')
        else:
            lines.append(f'\\quad {label} & {cell_c(key)} & {cell_s(d)} \\\\')
    lines.append('\\bottomrule')
    (R / 'gen/table_coverage_rows.tex').write_text('% generated by scripts/gen_coverage_table.py; do not edit by hand\n' + '\n'.join(lines) + '\n', encoding='utf-8')
    print('\n'.join(lines))
